def build_expanded():
    """Build expanded gazetteer from the comprehensive district list."""
    # Load existing gazetteer
    existing = {"states": {}, "places": {}}
    if os.path.exists(GAZETTEER_PATH):
        with open(GAZETTEER_PATH, "r", encoding="utf-8") as f:
            existing = json.load(f)

    places_dict = dict(existing.get("places", {}))
    states_dict = dict(existing.get("states", {}))

    # Add all districts
    added = 0
    for entry in ALL_DISTRICTS:
        name, state, lat, lon = entry
        key = name.lower()
        if key not in places_dict:
            places_dict[key] = {"state": state, "lat": lat, "lon": lon}
            added += 1

    data = {"states": states_dict, "places": places_dict}

    with open(GAZETTEER_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)

    print(f"Gazetteer expanded: added {added} new entries.")
    print(f"Total places: {len(places_dict)}, States: {len(states_dict)}")
    return len(places_dict)


if __name__ == "__main__":
    build_expanded()
